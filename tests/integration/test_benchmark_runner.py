"""Benchmark runner — smoke + contract tests.

The runner exists primarily to measure agent accuracy across a fixed set
of cases for the diploma evals (≥10 input/expected pairs, success rate).
These tests verify the runner itself: that it loads the JSON cases,
exercises the right component, and returns a `BenchmarkResult` with
counts + per-case verdicts. Real accuracy numbers come from running
`python -m benchmarks.run validator` against the live LLM — these
tests only confirm the plumbing works.
"""

from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
VALIDATOR_CASES = REPO_ROOT / "benchmarks" / "validator" / "cases.json"
DEPENDENCY_CASES = REPO_ROOT / "benchmarks" / "dependency" / "cases.json"
JUDGE_CASES = REPO_ROOT / "benchmarks" / "judge" / "cases.json"


# ── validator runner ──────────────────────────────────────────────────────────


async def test_validator_runner_loads_at_least_10_cases():
    from benchmarks.run import load_validator_cases

    cases = load_validator_cases(VALIDATOR_CASES)
    assert len(cases) >= 10, (
        f"validator benchmark requires ≥10 cases, found {len(cases)}"
    )


async def test_validator_runner_mock_llm_passes_pure_code_cases():
    """`--mock-llm` = LLM always accepts → all pure-code REJECT cases must
    still be rejected (by the prefilter), all LLM-accept cases pass, all
    LLM-reject cases (trolling) FAIL in mock mode. The runner must
    produce a real >0/<14 result — not a silent skip — so we get a real
    measurement of pure-code coverage.
    """
    from benchmarks.run import run_validator_benchmark

    result = await run_validator_benchmark(VALIDATOR_CASES, mock_llm=True)

    assert result.total >= 10
    # Pure-code rules must be 100% reliable — at minimum the ~7 pure-code
    # reject cases must all pass in mock mode.
    pure_code_passing = [
        d for d in result.details
        if d["name"].startswith(("empty-", "docs-", "autogenerated-", "oversized-"))
        and d["passed"]
    ]
    assert len(pure_code_passing) >= 6, (
        f"at least 6 pure-code cases must pass in mock mode; "
        f"passed: {[d['name'] for d in pure_code_passing]}"
    )
    # Trolling cases REJECT through LLM only — in mock mode they fail
    # (default to accept). That's the whole reason mock mode is useful:
    # the diff between mock-success-rate and real-success-rate measures
    # the LLM's contribution.
    trolling_failures = [
        d for d in result.details
        if d["name"].startswith("trolling-") and not d["passed"]
    ]
    assert len(trolling_failures) >= 1, (
        "at least one trolling case must fail in mock mode "
        "(LLM-required reject — mock can't catch it)"
    )


async def test_validator_runner_returns_success_rate():
    from benchmarks.run import run_validator_benchmark

    result = await run_validator_benchmark(VALIDATOR_CASES, mock_llm=True)

    assert 0.0 <= result.success_rate <= 1.0
    # Per-case details include name + expected + actual.
    for d in result.details:
        assert "name" in d
        assert "expected" in d
        assert "actual" in d
        assert "passed" in d


# ── dependency runner ─────────────────────────────────────────────────────────


async def test_dependency_runner_loads_at_least_10_cases():
    from benchmarks.run import load_dependency_cases

    cases = load_dependency_cases(DEPENDENCY_CASES)
    assert len(cases) >= 10


async def test_dependency_runner_full_pass_with_inline_osv_mocks():
    """OSV is mocked per case from the case's own `osv.querybatch` /
    `osv.vuln_details` payloads — runner must be 100% deterministic and
    pass every case. Anything less = bug in scanner OR in the case.
    """
    from benchmarks.run import run_dependency_benchmark

    result = await run_dependency_benchmark(DEPENDENCY_CASES)

    assert result.total >= 10
    # Deterministic runner: must hit 100% on its own canned cases.
    assert result.success_rate == 1.0, (
        f"dependency benchmark must pass 100% with inline OSV mocks; "
        f"got {result.passed}/{result.total} = {result.success_rate:.0%}. "
        f"Failures: {[d['name'] for d in result.details if not d['passed']]}"
    )


# ── judge runner ──────────────────────────────────────────────────────────────


async def test_judge_runner_loads_at_least_5_cases():
    from benchmarks.run import load_judge_cases

    payload = load_judge_cases(JUDGE_CASES)
    cases = payload["cases"]
    criteria = payload["criteria"]
    assert len(cases) >= 5, f"judge benchmark requires ≥5 calibration cases, got {len(cases)}"
    assert len(criteria) >= 3, "judge benchmark needs ≥3 rubric criteria"


async def test_judge_runner_mock_mode_passes_good_fails_bad():
    """In mock mode the judge always returns `{passed: true, all met}`.
    That correctly classifies 'good' calibration reports but misses
    every 'bad' one — by design. The gap is what we measure.
    """
    from benchmarks.run import run_judge_benchmark

    result = await run_judge_benchmark(JUDGE_CASES, mock_judge=True)

    good_passed = [
        d for d in result.details
        if d["name"].startswith("good-") and d["passed"]
    ]
    bad_failed_in_mock = [
        d for d in result.details
        if d["name"].startswith("bad-") and not d["passed"]
    ]
    assert len(good_passed) >= 2, (
        "mock judge must classify ≥2 'good' calibration reports as passing"
    )
    assert len(bad_failed_in_mock) >= 3, (
        "mock judge MUST miss most 'bad' calibration reports — that's the calibration gap"
    )


# ── benchmark result shape ────────────────────────────────────────────────────


def test_benchmark_result_is_renderable_as_text():
    from benchmarks.run import BenchmarkResult

    result = BenchmarkResult(
        suite="validator",
        details=[
            {"name": "case-a", "expected": "accepted", "actual": "accepted", "passed": True},
            {"name": "case-b", "expected": "rejected", "actual": "accepted", "passed": False},
        ],
    )

    assert result.total == 2
    assert result.passed == 1
    assert result.failed == 1
    assert result.success_rate == 0.5
    text = result.render()
    assert "validator" in text
    assert "1/2" in text or "50" in text
